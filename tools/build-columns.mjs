function replaceBetween(file, start, end, body) {
  const s = read(file);
  const a = s.indexOf(start);
  const b = s.indexOf(end);
  if (a < 0 || b < a) throw new Error(`${file}: ${start} / ${end} 표시를 찾을 수 없습니다`);
  write(file, s.slice(0, a + start.length) + '\n' + body + (body ? '\n' : '') + s.slice(b));
}

// ---- 1) article pages ----
const keep = new Set();
for (const p of POSTS) {
  write(fileOf(p), page(p));
  keep.add(fileOf(p));
}
const removed = [];
for (const f of fs.readdirSync(ROOT)) {
  if (!/^column-.+\.html$/.test(f) || keep.has(f)) continue;
  if (read(f).includes('generated by tools/build-columns.mjs')) {
    fs.unlinkSync(path.join(ROOT, f));
    removed.push(f);
  }
}

// ---- 2) sitemap ----
replaceBetween('sitemap.xml', '<!-- columns:start -->', '  <!-- columns:end -->',
  byDateDesc(POSTS).map((p) =>
    `  <url><loc>${urlOf(p)}</loc><lastmod>${isoDate(p.date)}</lastmod><changefreq>yearly</changefreq><priority>0.7</priority></url>`
  ).join('\n'));

// ---- 3) home preview: latest 3 ----
replaceBetween('index.html', '<!-- columns:latest:start -->', '<!-- columns:latest:end -->',
  byDateDesc(POSTS).slice(0, 3).map((p) => row(p, '        ')).join('\n'));

// ---- 4) column list: plain links for crawlers without JavaScript ----
replaceBetween('column.html', '<!-- columns:noscript:start -->', '<!-- columns:noscript:end -->',
  '<ul>\n' + byDateDesc(POSTS).map((p) =>
    `  <li><a href="${fileOf(p)}">${esc(p.title)}</a> — ${esc(p.excerpt)}</li>`
  ).join('\n') + '\n</ul>');

console.log(`칼럼 ${POSTS.length}편 생성: ${[...keep].join(', ')}`);
if (removed.length) console.log(`삭제: ${removed.join(', ')}`);
