// 메디컬 칼럼 글 페이지 생성기
//
//   node tools/build-columns.mjs
//
// columns-data.js 를 읽어서 아래를 다시 만듭니다. 칼럼을 추가·수정한 뒤 실행하고, 결과 파일을 함께 커밋합니다.
//   - column-<slug>.html  : 글마다 하나씩, 본문이 HTML 에 그대로 들어간 정적 페이지 (검색엔진 색인용)
//   - sitemap.xml         : <!-- columns:start --> ~ <!-- columns:end --> 사이
//   - index.html          : 홈 칼럼 미리보기 (최신 3편) <!-- columns:latest:start --> ~ end 사이
//   - column.html         : 자바스크립트 없이 읽는 크롤러용 링크 목록 <!-- columns:noscript:start --> ~ end 사이
// columns-data.js 에서 빠진 글의 페이지는 지웁니다 (이 생성기가 만든 파일만).

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// TODO: 도메인 확정 후 실제 도메인으로 교체 (sitemap.xml · 각 페이지 canonical 과 함께)
const SITE = 'https://all-detail-clinic.vercel.app';
const OG_IMAGE = SITE + '/images/int-reception.jpg';
const AUTHOR = { name: '조주형', title: '대표원장' };
const CLINIC = '올디테일의원';
const GENERATED = '<!-- generated by tools/build-columns.mjs from columns-data.js — 직접 고치지 말고 columns-data.js 를 수정한 뒤 다시 생성하세요 -->';

const CAT_KO = {
  LIFTING: '리프팅',
  COMFORT: '통증과 마취',
  PIGMENT: '색소',
  BOOSTER: '스킨부스터',
  DESIGN: '디자인',
  INSIGHT: '인사이트'
};

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const EOL = '\r\n';

const read = (f) => fs.readFileSync(path.join(ROOT, f), 'utf8');
const write = (f, s) => fs.writeFileSync(path.join(ROOT, f), s.replace(/\r?\n/g, EOL), 'utf8');

// columns-data.js is a browser ES module; load it the same way regardless of Node's module settings
const src = read('columns-data.js');
const { POSTS } = await import('data:text/javascript;charset=utf-8,' + encodeURIComponent(src));

const esc = (s) => String(s)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;').replace(/'/g, '&#39;');
const isoDate = (d) => d.replace(/\./g, '-');
const fileOf = (p) => 'column-' + p.slug + '.html';
const urlOf = (p) => SITE + '/column-' + p.slug;
const byDateDesc = (list) => list.slice().sort((a, b) => b.date.localeCompare(a.date));
const jsonLd = (o) => JSON.stringify(o, null, 2).replace(/</g, '\\u003c');

// ---- checks ----
const seen = new Set();
for (const p of POSTS) {
  for (const k of ['cat', 'date', 'slug', 'title', 'excerpt', 'body']) {
    if (!p[k]) throw new Error(`columns-data.js: "${p.title || p.slug}" 에 ${k} 가 없습니다`);
  }
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(p.slug)) throw new Error(`slug 는 영문 소문자 · 숫자 · 하이픈만: ${p.slug}`);
  if (seen.has(p.slug)) throw new Error(`slug 중복: ${p.slug}`);
  if (!CAT_KO[p.cat]) throw new Error(`알 수 없는 cat: ${p.cat} (${p.slug})`);
  if (!/^\d{4}\.\d{2}\.\d{2}$/.test(p.date)) throw new Error(`date 형식은 YYYY.MM.DD: ${p.date} (${p.slug})`);
  seen.add(p.slug);
}

// ---- pieces ----
const ROW_STYLE = 'display: grid; grid-template-columns: minmax(0, 1fr) auto; gap: 20px; align-items: baseline; padding: clamp(20px, 3vh, 32px) 4px; border-bottom: 1px solid #E4E9E6; color: #121614;';

function row(p, indent) {
  return [
    `<a href="${fileOf(p)}" style="${ROW_STYLE}" style-hover="background: #F2F5F3; color: #121614;">`,
    `  <span>`,
    `    <span style="display: block; margin-bottom: 10px; font-size: 10.5px; letter-spacing: 0.18em; color: #2C7A6B;">${esc(p.cat)}</span>`,
    `    <span style="display: block; font-size: clamp(19px, 2.1vw, 28px); font-weight: 600; letter-spacing: -0.04em; line-height: 1.4;">${esc(p.title)}</span>`,
    `    <span style="display: block; margin-top: 10px; font-size: 13.5px; line-height: 1.85; color: #6A736F; max-width: 680px;">${esc(p.excerpt)}</span>`,
    `  </span>`,
    `  <span style="font-family: 'Newsreader', serif; font-size: 13px; color: #8B948F; white-space: nowrap;">${esc(p.date)}</span>`,
    `</a>`
  ].map((l) => indent + l).join('\n');
}

function block([kind, text]) {
  const inner = {
    h: `<h2 style="margin: 44px 0 16px; font-size: clamp(18px, 1.8vw, 23px); font-weight: 600; letter-spacing: -0.035em; line-height: 1.5;">${esc(text)}</h2>`,
    b: `<p style="margin: 0; font-size: 15.5px; line-height: 2.05; color: #37413D;">${esc(text)}</p>`,
    n: `<p style="margin: 0; padding: 18px 20px; background: #F1F5F3; font-size: 14px; line-height: 1.95; color: #4C5652;">${esc(text)}</p>`
  }[kind];
  if (!inner) throw new Error(`알 수 없는 본문 종류: ${kind}`);
  return `            <div style="margin-bottom: 30px; max-width: 720px;">\n              ${inner}\n            </div>`;
}

function related(p) {
  const others = byDateDesc(POSTS.filter((x) => x !== p));
  const same = others.filter((x) => x.cat === p.cat);
  return [...same, ...others.filter((x) => x.cat !== p.cat)].slice(0, 3);
}

